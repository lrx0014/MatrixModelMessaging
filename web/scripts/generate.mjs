import fs from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const expectedNode = (await fs.readFile(new URL('../../.node-version', import.meta.url), 'utf8')).trim();
if (process.versions.node !== expectedNode) {
  throw new Error(`Use pinned Node ${expectedNode}; found ${process.versions.node}`);
}
const output = new URL('../src/generated/api.ts', import.meta.url);
const schema = await openapiTS(new URL('../../api/openapi.json', import.meta.url), { alphabetize: true });
const expected = '// Generated by cargo xtask contracts. Do not edit.\n' + astToString(schema);
if (process.argv.includes('--check')) {
  if (await fs.readFile(output, 'utf8') !== expected) {
    throw new Error('TypeScript contract is stale; run cargo xtask contracts');
  }
} else {
  await fs.writeFile(output, expected);
}
